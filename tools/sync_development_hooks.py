"""Snapshot installed vanilla + enabled-mod development hooks for parity testing.

Run from the mod directory, or supply --game and --user-dir. No game files change.
This does not replace the engine's on_actions; only our one-step worker calls it.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re
import zipfile

TOKEN = re.compile(r'"(?:\\.|[^"\\])*"|#[^\n]*|[{}]|[^\s{}=]+|=')


def blocks(source):
    tokens = [m for m in TOKEN.finditer(source) if not m.group().startswith('#')]
    depth = 0
    for i, token in enumerate(tokens):
        word = token.group()
        if word == '{':
            if depth == 0 and i >= 2 and tokens[i-1].group() == '=':
                name, start = tokens[i-2].group(), token.end()
            depth += 1
        elif word == '}':
            depth -= 1
            if depth < 0:
                raise ValueError('Unbalanced source')
            if depth == 0:
                yield name, source[start:token.start()]
    if depth:
        raise ValueError('Unbalanced source')


def influence_tree(low, high, indent=4):
    """Literal thresholds: EU4 rejects a variable influence argument."""
    pad = ' ' * indent
    if high - low == 1:
        return [f'{pad}set_variable = {{ which = dicm_bh_sp_estate_weight value = {low} }}']
    mid = (low + high) // 2
    return ([f'{pad}if = {{',
             f'{pad}    limit = {{ estate_influence = {{ estate = $ESTATE$ influence = {mid} }} }}']
            + influence_tree(mid, high, indent + 4)
            + [f'{pad}}}', f'{pad}else = {{']
            + influence_tree(low, mid, indent + 4) + [f'{pad}}}'])


def estate_effects(estates):
    out = ['# GENERATED by tools/sync_development_hooks.py.',
           '# User-approved whole-number influence approximation; native event scope only.',
           '# Snapshot all weights before applying any land changes.',
           'dicm_bh_sp_read_estate_weight = {'] + influence_tree(0, 256) + ['}',
           'dicm_bh_sp_estate_land_piece = {',
           '    if = {',
           '        limit = { check_variable = { which = dicm_bh_sp_estate_units value = $UNITS$ } }',
           '        change_estate_land_share = { estate = $ESTATE$ share = $DELTA$ }',
           '        subtract_variable = { which = dicm_bh_sp_estate_units value = $UNITS$ }',
           '    }', '}', 'dicm_bh_sp_apply_estate_land = {',
           '    set_variable = { which = dicm_bh_sp_estate_total value = 0 }']
    for estate in estates:
        out += ['    if = {', f'        limit = {{ has_estate = {estate} }}',
                f'        dicm_bh_sp_read_estate_weight = {{ ESTATE = {estate} }}',
                f'        set_variable = {{ which = dicm_bh_sp_weight_{estate} which = dicm_bh_sp_estate_weight }}',
                '        change_variable = { which = dicm_bh_sp_estate_total which = dicm_bh_sp_estate_weight }', '    }']
    out += ['    if = {',
            '        limit = { check_variable = { which = dicm_bh_sp_estate_total value = 1 } }']
    for estate in estates:
        out += ['        if = {', f'            limit = {{ has_estate = {estate} }}',
                f'            set_variable = {{ which = dicm_bh_sp_estate_units which = dicm_bh_sp_weight_{estate} }}',
                '            multiply_variable = { which = dicm_bh_sp_estate_units value = 200 }',
                '            divide_variable = { which = dicm_bh_sp_estate_units which = dicm_bh_sp_estate_total }',
                '            round_variable = { which = dicm_bh_sp_estate_units value = -1 }']
        for units in (128, 64, 32, 16, 8, 4, 2, 1):
            out.append(f'            dicm_bh_sp_estate_land_piece = {{ ESTATE = {estate} UNITS = {units} DELTA = -{units / 1000:.3f} }}')
        out += ['        }']
    return '\n'.join(out + ['    }', '}']) + '\n'


def generate(game, user_dir, destination):
    roots = [('vanilla', game)]
    archives_checked = []
    config = json.loads((user_dir / 'dlc_load.json').read_text(encoding='utf-8-sig'))
    for descriptor in config['enabled_mods']:
        p = user_dir / descriptor
        descriptor_text = p.read_text(encoding='utf-8-sig')
        match = re.search(r'path\s*=\s*"([^"]+)"', descriptor_text)
        if not match:
            archive = re.search(r'archive\s*=\s*"([^"]+)"', descriptor_text)
            if not archive:
                raise ValueError(f'Cannot resolve enabled mod: {p}')
            with zipfile.ZipFile(archive[1]) as bundle:
                relevant = [n for n in bundle.namelist() if n.startswith(('common/on_actions/', 'common/estate_privileges/', 'common/estates/')) and n.endswith('.txt')]
            if relevant:
                raise ValueError(f'Archive has relevant scripts; adapt generator: {archive[1]}: {relevant}')
            archives_checked.append(archive[1])
            continue
        path = Path(match[1])
        if not path.is_absolute():
            path = user_dir / path
        if path.resolve() != destination.resolve():
            roots.append((p.name, path))
    manifest = {'sources': [], 'protected_privileges': [], 'archives_checked': archives_checked}
    hooks = {kind: [] for kind in ('adm', 'dip', 'mil')}
    estates = set()
    for folder in ('on_actions', 'estate_privileges', 'estates'):
        effective = {}
        for label, root in roots:
            for p in sorted((root / 'common' / folder).glob('*.txt')):
                effective[p.name] = (label, p)
        for label, p in sorted(effective.values(), key=lambda pair: pair[1].name):
            try:
                source = p.read_text(encoding='utf-8-sig')
            except UnicodeDecodeError:
                source = p.read_text(encoding='cp1252')
            relevant = False
            for name, body in blocks(source):
                if folder == 'on_actions':
                    match = re.fullmatch(r'on_(adm|dip|mil)_development', name)
                    if match:
                        if re.search(r'\b(?:random_events|events)\s*=', body):
                            raise ValueError(f'Event lists need explicit adaptation: {p}')
                        hooks[match[1]].append((label, p.name, body))
                        relevant = True
                elif folder == 'estates':
                    if not re.fullmatch(r'[A-Za-z_][A-Za-z_0-9]*', name):
                        raise ValueError(f'Unexpected estate definition: {p}: {name}')
                    estates.add(name)
                    relevant = True
                elif 'no_estate_crownland_loss_from_developing' in body:
                    manifest['protected_privileges'].append(name)
                    relevant = True
            if relevant:
                manifest['sources'].append({'path': str(p), 'sha256': hashlib.sha256(p.read_bytes()).hexdigest()})
    output = ['# GENERATED by tools/sync_development_hooks.py. Do not edit by hand.',
              '# Province ROOT and province FROM, matching the observed native development hook scopes.',
              '# No engine on_actions are overridden. Runtime parity remains to be tested.']
    for kind, entries in hooks.items():
        if not entries:
            raise ValueError(f'No {kind} hooks found')
        output.append(f'dicm_bh_sp_replay_{kind}_hooks = {{')
        for label, filename, body in entries:
            output.append(f'    # Source: {label}/common/on_actions/{filename}')
            output.append(body.strip('\r\n'))
        output.append('}\n')
    out = destination / 'common/scripted_effects/dicm_bh_development_hook_replay.txt'
    out.write_text('\n'.join(output)+'\n', encoding='utf-8', newline='\r\n')
    guard = ['# Initial parity implementation rejects protected-estate mechanics.',
             '# Native proportional estate deductions need a separate comparison.',
             'dicm_bh_sp_estates_supported = {', '    NOT = { OR = {']
    guard += [f'        has_estate_privilege = {name}' for name in sorted(set(manifest['protected_privileges']))]
    guard += ['    } }']
    for estate in sorted(estates):
        guard += ['    NOT = { AND = {', f'        has_estate = {estate}',
                  f'        OR = {{ estate_influence = {{ estate = {estate} influence = 256 }}',
                  f'            NOT = {{ estate_influence = {{ estate = {estate} influence = 0 }} }} }}',
                  '    } }']
    guard += ['}']
    (destination / 'common/scripted_triggers/dicm_bh_development_spend_triggers.txt').write_text('\n'.join(guard)+'\n', encoding='utf-8', newline='\r\n')
    manifest['estates'] = sorted(estates)
    (destination / 'common/scripted_effects/dicm_bh_development_estate_effects.txt').write_text(estate_effects(sorted(estates)), encoding='utf-8', newline='\r\n')
    (destination / 'tools/development_hook_sources.json').write_text(json.dumps(manifest, indent=2)+'\n', encoding='utf-8')
    print('Generated replay:', {k: len(v) for k, v in hooks.items()}, '; protected privileges:', len(set(manifest['protected_privileges'])))


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--game', type=Path, default=Path('D:/SteamLibrary/steamapps/common/Europa Universalis IV'))
    parser.add_argument('--user-dir', type=Path, default=Path(__file__).resolve().parents[3])
    args = parser.parse_args()
    generate(args.game, args.user_dir, Path(__file__).resolve().parents[1])
